#!/usr/bin/env python3
"""Render TP1 mixed dynamic-precision tables and plots from actual block results."""

from __future__ import annotations

import json
import subprocess
from dataclasses import dataclass
from pathlib import Path

import matplotlib.pyplot as plt


ROOT = Path(__file__).resolve().parent
BASELINE_RESULTS = ROOT / "latency-results"
DYNAMIC_RESULTS = ROOT / "latency-results-dynamic-precision"
CONFIG_ROOT = ROOT / "configs-dynamic-precision"
OUTPUT_ROOT = ROOT / "latency-results-dynamic-precision"
BATCH_SIZES = [1, 4, 8, 16, 32, 64, 128, 256, 512]


@dataclass(frozen=True)
class DynamicConfig:
    name: str
    model_label: str
    source_model: str
    tp_size: int
    kv_len: int
    scope: str


def load_config(path: Path) -> DynamicConfig:
    raw = json.loads(path.read_text(encoding="utf-8"))
    return DynamicConfig(
        name=raw["name"],
        model_label=raw["model_label"],
        source_model=raw["source_model"],
        tp_size=int(raw["tp_size"]),
        kv_len=int(raw["kv_len"]),
        scope=raw["scope"],
    )


def load_baseline_us(config: DynamicConfig, batch_size: int, precision: str) -> float:
    path = (
        BASELINE_RESULTS
        / config.source_model
        / f"tp{config.tp_size}"
        / f"kv{config.kv_len}"
        / f"bs{batch_size}"
        / precision
        / f"{config.scope}.json"
    )
    data = json.loads(path.read_text(encoding="utf-8"))
    return float(data["median_us"])


def load_dynamic_result(config: DynamicConfig, batch_size: int) -> dict:
    path = (
        DYNAMIC_RESULTS
        / config.name
        / f"tp{config.tp_size}"
        / f"kv{config.kv_len}"
        / f"bs{batch_size}"
        / "dynamic"
        / f"{config.scope}.json"
    )
    return json.loads(path.read_text(encoding="utf-8"))


def collect_rows(config: DynamicConfig) -> list[dict]:
    rows: list[dict] = []
    for batch_size in BATCH_SIZES:
        bf16_us = load_baseline_us(config, batch_size, "bf16")
        marlin_us = load_baseline_us(config, batch_size, "marlin")
        dynamic = load_dynamic_result(config, batch_size)
        dynamic_us = float(dynamic["median_us"])
        rows.append(
            {
                "batch_size": batch_size,
                "bf16_us": bf16_us,
                "marlin_us": marlin_us,
                "dynamic_us": dynamic_us,
                "projection_precisions": dynamic["projection_precisions"],
                "speedup_vs_bf16": bf16_us / dynamic_us,
                "speedup_vs_marlin": marlin_us / dynamic_us,
            }
        )
    return rows


def format_time(value: float) -> str:
    return f"{value:.1f}"


def format_speedup(value: float) -> str:
    return f"x{value:.2f}"


def render_table(config: DynamicConfig, rows: list[dict]) -> str:
    lines = [
        "\\begin{table}[ht]",
        "\\centering",
        "\\begin{tabular}{rccccc}",
        "\\toprule",
        " & \\multicolumn{3}{c}{Block Time (\\textmu s)} & \\multicolumn{2}{c}{Speedup} \\\\",
        "Batch & BF16 & Marlin INT4 & Dynamic Precision & vs BF16 & vs Marlin INT4 \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            " & ".join(
                [
                    str(row["batch_size"]),
                    format_time(row["bf16_us"]),
                    format_time(row["marlin_us"]),
                    format_time(row["dynamic_us"]),
                    format_speedup(row["speedup_vs_bf16"]),
                    format_speedup(row["speedup_vs_marlin"]),
                ]
            )
            + " \\\\"
        )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            (
                f"\\caption{{{config.model_label} decode block latency with actual mixed per-projection "
                "dynamic precision. BF16 and Marlin INT4 are uniform baselines; dynamic precision uses the "
                "JSON-configured heterogeneous assignment for qkv, o, up, and down at each batch.}"
            ),
            f"\\label{{tab:{config.name.replace('.', '').replace('-', '')}-dynamic-precision}}",
            "\\end{table}",
        ]
    )
    return "\n".join(lines)


def render_tables(configs: list[DynamicConfig], results: dict[str, list[dict]]) -> Path:
    tables_path = OUTPUT_ROOT / "tables.tex"
    sections = ["% Auto-generated by render_dynamic_precision_results.py", ""]
    for config in configs:
        sections.append(f"% {config.model_label}")
        sections.append(render_table(config, results[config.name]))
        sections.append("")
    tables_path.write_text("\n".join(sections).rstrip() + "\n", encoding="utf-8")
    return tables_path


def compile_pdf(tables_path: Path) -> Path:
    wrapper_path = OUTPUT_ROOT / "tables_wrapper.tex"
    wrapper_path.write_text(
        "\n".join(
            [
                "\\documentclass{article}",
                "\\usepackage[margin=0.5in]{geometry}",
                "\\usepackage{booktabs}",
                "\\begin{document}",
                f"\\input{{{tables_path.name}}}",
                "\\end{document}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    subprocess.run(
        ["pdflatex", "-interaction=nonstopmode", wrapper_path.name],
        cwd=OUTPUT_ROOT,
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    return OUTPUT_ROOT / "tables_wrapper.pdf"


def render_plot(configs: list[DynamicConfig], results: dict[str, list[dict]]) -> tuple[Path, Path]:
    plt.rcParams.update(
        {
            "font.size": 10,
            "axes.titlesize": 11,
            "axes.labelsize": 10,
            "legend.fontsize": 9,
        }
    )
    fig, axes = plt.subplots(1, len(configs), figsize=(12, 4.2), constrained_layout=True)
    if len(configs) == 1:
        axes = [axes]
    for ax, config in zip(axes, configs, strict=True):
        rows = results[config.name]
        ax.plot(
            BATCH_SIZES,
            [row["speedup_vs_bf16"] for row in rows],
            label="Dynamic vs BF16",
            color="#2563eb",
            linestyle="-",
            linewidth=2.0,
            marker="o",
            markersize=4,
        )
        ax.plot(
            BATCH_SIZES,
            [row["speedup_vs_marlin"] for row in rows],
            label="Dynamic vs Marlin INT4",
            color="#d97706",
            linestyle="--",
            linewidth=2.0,
            marker="s",
            markersize=4,
        )
        ax.set_title(config.model_label)
        ax.set_xscale("log", base=2)
        ax.set_xticks(BATCH_SIZES, [str(x) for x in BATCH_SIZES])
        ax.set_xlabel("Batch Size")
        ax.set_ylabel("Speedup")
        ax.grid(True, which="major", alpha=0.25)
        ax.axhline(1.0, color="black", linewidth=1.0, alpha=0.5)
        ax.legend(loc="best", frameon=False)
    pdf_path = OUTPUT_ROOT / "dynamic_precision_speedup.pdf"
    png_path = OUTPUT_ROOT / "dynamic_precision_speedup.png"
    fig.savefig(pdf_path, bbox_inches="tight")
    fig.savefig(png_path, dpi=200, bbox_inches="tight")
    plt.close(fig)
    return pdf_path, png_path


def main() -> None:
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    configs = sorted((load_config(path) for path in CONFIG_ROOT.glob("*.json")), key=lambda x: x.name)
    results = {config.name: collect_rows(config) for config in configs}
    tables_path = render_tables(configs, results)
    pdf_path = compile_pdf(tables_path)
    plot_pdf, plot_png = render_plot(configs, results)
    print(tables_path)
    print(pdf_path)
    print(plot_pdf)
    print(plot_png)


if __name__ == "__main__":
    main()
