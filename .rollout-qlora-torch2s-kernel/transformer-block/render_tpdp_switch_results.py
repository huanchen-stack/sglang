#!/usr/bin/env python3
"""Render Qwen2.5-32B TP/DP switch table and plot."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import matplotlib.pyplot as plt


ROOT = Path(__file__).resolve().parent
SOURCE_ROOT = ROOT / "latency-results" / "qwen2.5-32b"
OUTPUT_ROOT = ROOT / "latency-results-tpdp-switch"
BATCH_SIZES = [1, 4, 8, 16, 32, 64, 128, 256, 512]


def load_median(tp: str, precision: str, batch_size: int) -> float:
    path = SOURCE_ROOT / tp / "kv1024" / f"bs{batch_size}" / precision / "block.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    return float(data["median_us"])


def collect_rows() -> list[dict]:
    qlora_tp1_lookup = {
        batch_size: load_median("tp1", "qlora", batch_size) for batch_size in BATCH_SIZES
    }
    rows: list[dict] = []
    for batch_size in BATCH_SIZES:
        bf16_tp4 = load_median("tp4", "bf16", batch_size)
        qlora_tp1 = load_median("tp1", "qlora", batch_size)
        lookup_batch = batch_size // 4 if batch_size % 4 == 0 else None
        qlora_dp_equiv = (
            qlora_tp1_lookup[lookup_batch] / 4.0
            if lookup_batch in qlora_tp1_lookup
            else None
        )
        qlora_tp4 = load_median("tp4", "qlora", batch_size)
        rows.append(
            {
                "batch_size": batch_size,
                "bf16_tp4_us": bf16_tp4,
                "qlora_tp1_us": qlora_tp1,
                "qlora_dp_equiv_us": qlora_dp_equiv,
                "dp_lookup_batch": lookup_batch,
                "qlora_tp4_us": qlora_tp4,
                "dp_equiv_speedup_vs_bf16_tp4": (
                    None if qlora_dp_equiv is None else bf16_tp4 / qlora_dp_equiv
                ),
                "tp4_speedup_vs_bf16_tp4": bf16_tp4 / qlora_tp4,
            }
        )
    return rows


def write_rows(rows: list[dict]) -> None:
    for row in rows:
        out = OUTPUT_ROOT / "qwen2.5-32b" / "tpdp-switch" / f"bs{row['batch_size']}" / "block.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(row, indent=2) + "\n", encoding="utf-8")


def render_table(rows: list[dict]) -> Path:
    tables_path = OUTPUT_ROOT / "tables.tex"
    lines = [
        "% Auto-generated by render_tpdp_switch_results.py",
        "",
        "\\begin{table}[ht]",
        "\\centering",
        "\\begin{tabular}{rcccccc}",
        "\\toprule",
        " & \\multicolumn{4}{c}{Block Time (\\textmu s)} & \\multicolumn{2}{c}{Speedup} \\\\",
        "Batch & BF16 TP4 & QLoRA TP1 & QLoRA DP-Equiv & QLoRA TP4 & DP-Equiv vs BF16 TP4 & QLoRA TP4 vs BF16 TP4 \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            " & ".join(
                [
                    str(row["batch_size"]),
                    f"{row['bf16_tp4_us']:.1f}",
                    f"{row['qlora_tp1_us']:.1f}",
                    "-" if row["qlora_dp_equiv_us"] is None else f"{row['qlora_dp_equiv_us']:.1f}",
                    f"{row['qlora_tp4_us']:.1f}",
                    (
                        "-"
                        if row["dp_equiv_speedup_vs_bf16_tp4"] is None
                        else f"x{row['dp_equiv_speedup_vs_bf16_tp4']:.2f}"
                    ),
                    f"x{row['tp4_speedup_vs_bf16_tp4']:.2f}",
                ]
            )
            + " \\\\"
        )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            (
                "\\caption{Qwen2.5 32B TP/DP switch comparison for decode block latency. "
                "QLoRA DP-Equiv is defined as one quarter of measured QLoRA TP1 latency at batch size equal to one quarter of the current batch. "
                "If that lookup batch is not in the benchmark set, the entry is omitted.}"
            ),
            "\\label{tab:qwen2532b-tpdp-switch}",
            "\\end{table}",
            "",
        ]
    )
    tables_path.write_text("\n".join(lines), encoding="utf-8")
    return tables_path


def compile_pdf(tables_path: Path) -> Path:
    wrapper = OUTPUT_ROOT / "tables_wrapper.tex"
    wrapper.write_text(
        "\n".join(
            [
                "\\documentclass{article}",
                "\\usepackage[margin=0.5in]{geometry}",
                "\\usepackage{booktabs}",
                "\\begin{document}",
                f"\\input{{{tables_path.name}}}",
                "\\end{document}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    subprocess.run(
        ["pdflatex", "-interaction=nonstopmode", wrapper.name],
        cwd=OUTPUT_ROOT,
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    return OUTPUT_ROOT / "tables_wrapper.pdf"


def render_plot(rows: list[dict]) -> tuple[Path, Path]:
    plt.rcParams.update(
        {
            "font.size": 10,
            "axes.titlesize": 11,
            "axes.labelsize": 10,
            "legend.fontsize": 9,
        }
    )
    fig, ax = plt.subplots(figsize=(7.2, 4.6), constrained_layout=True)
    ax.plot(
        BATCH_SIZES,
        [row["bf16_tp4_us"] for row in rows],
        label="BF16 TP4",
        color="#2563eb",
        linestyle="-",
        linewidth=2.0,
        marker="o",
        markersize=4,
    )
    dp_rows = [row for row in rows if row["qlora_dp_equiv_us"] is not None]
    ax.plot(
        [row["batch_size"] for row in dp_rows],
        [row["qlora_dp_equiv_us"] for row in dp_rows],
        label="QLoRA DP-Equiv",
        color="#d97706",
        linestyle="--",
        linewidth=2.0,
        marker="s",
        markersize=4,
    )
    ax.plot(
        BATCH_SIZES,
        [row["qlora_tp4_us"] for row in rows],
        label="QLoRA TP4",
        color="#059669",
        linestyle="-.",
        linewidth=2.0,
        marker="^",
        markersize=4,
    )
    ax.set_title("Qwen2.5 32B: BF16 TP4 vs QLoRA DP/TP")
    ax.set_xscale("log", base=2)
    ax.set_xticks(BATCH_SIZES, [str(x) for x in BATCH_SIZES])
    ax.set_xlabel("Batch Size")
    ax.set_ylabel("Block Latency (us)")
    ax.grid(True, which="major", alpha=0.25)
    ax.legend(loc="best", frameon=False)
    pdf_path = OUTPUT_ROOT / "tpdp_switch_latency.pdf"
    png_path = OUTPUT_ROOT / "tpdp_switch_latency.png"
    fig.savefig(pdf_path, bbox_inches="tight")
    fig.savefig(png_path, dpi=200, bbox_inches="tight")
    plt.close(fig)
    return pdf_path, png_path


def main() -> None:
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    rows = collect_rows()
    write_rows(rows)
    tables = render_table(rows)
    pdf = compile_pdf(tables)
    plot_pdf, plot_png = render_plot(rows)
    print(tables)
    print(pdf)
    print(plot_pdf)
    print(plot_png)


if __name__ == "__main__":
    main()
